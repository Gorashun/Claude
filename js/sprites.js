  /* ==========================================================
     COMBAT BACKGROUND
     ========================================================== */
  function drawCombatBackground(ctx, terrain, width, height) {
    let top, bottom;
    switch (terrain) {
      case 'dungeon':  top = '#080004'; bottom = '#1a0008'; break;
      case 'forest':   top = '#001200'; bottom = '#002800'; break;
      case 'mountain': top = '#100d08'; bottom = '#2a2010'; break;
      case 'water':    top = '#000820'; bottom = '#001840'; break;
      case 'swamp':    top = '#020a02'; bottom = '#050f05'; break;
      default:         top = '#040a04'; bottom = '#0a1208'; break;
    }
    const grad = ctx.createLinearGradient(0, 0, 0, height);
    grad.addColorStop(0, top);
    grad.addColorStop(1, bottom);
    ctx.fillStyle = grad;
    ctx.fillRect(0, 0, width, height);
    // Ground lines
    ctx.strokeStyle = terrain === 'dungeon' ? '#330000' : '#003300';
    ctx.lineWidth = 1;
    for (let y = Math.floor(height * 0.65); y < height; y += 5) {
      ctx.globalAlpha = 0.3;
      ctx.beginPath(); ctx.moveTo(0, y); ctx.lineTo(width, y); ctx.stroke();
    }
    ctx.globalAlpha = 1;
  }

